def parse():
    """Turn the block of text above into a list of (name, description)."""
    out = []
    for line in STYLES.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        if "|" in line:
            name, description = line.split("|", 1)
            out.append((name.strip(), description.strip()))
        else:
            out.append((line, ""))
    return out


def render_list():
    """Build the numbered HTML list for the article."""
    items = []

    for name, description in parse():
        body = f"<strong>{name}</strong>"
        if description:
            body += f" &mdash; {description}"

        if name in SUBLISTS:
            subs = "".join(f"<li>{s}</li>" for s in SUBLISTS[name])
            body += (
                '<ul style="margin-top:.6em;margin-bottom:.2em">'
                f"{subs}</ul>"
            )

        items.append(f"          <li>{body}</li>")

    return (
        '        <ol class="style-list">\n'
        + "\n".join(items)
        + "\n        </ol>"
    )


